package JavaMethods3;
import java.util.Scanner;

public class StaticMethod {

    public static boolean isPerfect(int number) {
        int sum = 0;
        for (int i = 1; i <= number / 2; i++) {
            if (number % i == 0) sum += i;
        }
        return sum == number;
    }

    public static boolean isAbundant(int number) {
        int sum = 0;
        for (int i = 1; i <= number / 2; i++) {
            if (number % i == 0) sum += i;
        }
        return sum > number;
    }

    public static boolean isDeficient(int number) {
        int sum = 0;
        for (int i = 1; i <= number / 2; i++) {
            if (number % i == 0) sum += i;
        }
        return sum < number;
    }

    public static int factorial(int n) {
        int fact = 1;
        for (int i = 2; i <= n; i++) fact *= i;
        return fact;
    }

    public static boolean isStrong(int number) {
        int sum = 0;
        int temp = number;
        while (temp > 0) {
            int digit = temp % 10;
            sum += factorial(digit);
            temp /= 10;
        }
        return sum == number;
    }

    public static void main(String[] args) {
        Scanner scanner = new Scanner(System.in);
        System.out.print("Enter a number: ");
        int number = scanner.nextInt();

        System.out.println("\nResults:");
        System.out.println("Perfect Number: " + (isPerfect(number) ? "Yes" : "No"));
        System.out.println("Abundant Number: " + (isAbundant(number) ? "Yes" : "No"));
        System.out.println("Deficient Number: " + (isDeficient(number) ? "Yes" : "No"));
        System.out.println("Strong Number: " + (isStrong(number) ? "Yes" : "No"));

        scanner.close();
    }
}
